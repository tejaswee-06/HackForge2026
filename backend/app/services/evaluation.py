"""Reproducible evaluation: ASTRA ranking vs. a simple baseline on labelled synthetic scenarios.

Every scenario is generated by ``astra_intel.simulation`` and runs through the SAME Person 1
normalizer and Person 2 engine as the application. Ground-truth labels are used only here.

Baseline: direct time-ignoring reachability from the origin, ranked by BFS hop count, then address
(the "simple graph reachability" baseline named in the blueprint, section 12.3).

Metrics (denominators reported):
  precision@k   relevant leads in the top k / k                       (incident scenarios)
  recall@k      relevant leads in the top k / all relevant addresses  (incident scenarios)
  average precision over the full ranking                             (incident scenarios)
  service-in-top-k rate   fraction of incident scenarios with a labelled service hub in the top k
  case hypothesis accuracy: leading case hypothesis == expected (H1 incident / H2 benign / H3 insufficient)
  benign false-positive rate: benign scenarios whose leading case hypothesis is H1
  runtime per scenario (wall clock, this machine)
These are measurements on a controlled synthetic generator; they do NOT estimate real-world accuracy.
"""
from __future__ import annotations

import platform
import time
from collections import deque
from datetime import datetime, timezone
from typing import Any, Optional

from astra_intel import dsa
from astra_intel.engine import AnalysisConfig, analyze
from astra_intel.simulation import generate

from ..schemas.common import SourceRef
from ..schemas.intel import SimulationCreate
from .ingestion.normalizer import normalize_batch
from .osint_ingest.service import build_document


def run_scenario(sim_cfg: dict, cfg: Optional[AnalysisConfig] = None) -> tuple[dict, dict, Any]:
    g = generate(sim_cfg)
    src = SourceRef(provider="astra-simulator", data_mode="synthetic",
                    retrieved_at=datetime.fromisoformat(g["metadata"]["start_time"].replace("Z", "+00:00")),
                    reference=g["scenario_id"])
    nb = normalize_batch(g["native_rows"], g["erc20_rows"], 1, src)
    docs = [build_document(d, data_mode="synthetic", extraction_method="simulated_text_v1").model_dump()
            for d in g["documents"]]
    res = analyze(investigation_id=g["scenario_id"], chain_id=1, start_address=g["start_address"], events=nb.events,
                  documents=docs, data_mode="synthetic", dataset_ref=g["scenario_id"], config=cfg)
    return g, res, nb


def baseline_ranking(events, start_address: str) -> list[str]:
    edges = [(dsa.node_id(1, e.from_address), dsa.node_id(1, e.to_address)) for e in events if e.status == "success"]
    adj: dict[str, set] = {}
    for u, v in edges:
        adj.setdefault(u, set()).add(v)
    s = dsa.node_id(1, start_address)
    dist = {s: 0}
    q = deque([s])
    while q:
        n = q.popleft()
        for m in sorted(adj.get(n, ())):
            if m not in dist:
                dist[m] = dist[n] + 1
                q.append(m)
    return [n.split(":", 1)[1] for n, _ in sorted(dist.items(), key=lambda kv: (kv[1], kv[0])) if n != s]


def _ap(ranked: list[str], rel: set[str]) -> Optional[float]:
    if not rel:
        return None
    hits, s = 0, 0.0
    for i, a in enumerate(ranked, 1):
        if a in rel:
            hits += 1
            s += hits / i
    return s / len(rel)


def run_benchmark(seeds: list[int], *, ks=(5, 10), kinds=("incident", "benign", "insufficient"),
                  sim_overrides: Optional[dict] = None) -> dict:
    per: list[dict] = []
    for kind in kinds:
        for seed in seeds:
            sc = SimulationCreate(seed=seed, scenario_kind=kind, **(sim_overrides or {})).model_dump()
            t = time.perf_counter()
            g, res, nb = run_scenario(sc)
            dt = time.perf_counter() - t
            gt = g["ground_truth"]
            rel, svc = set(gt["relevant_addresses"]), set(gt["service_addresses"])
            astra = [L["address"] for L in res["leads"]]
            base = baseline_ranking(nb.events, g["start_address"])
            row = {"scenario_id": g["scenario_id"], "kind": kind, "seed": seed, "events": len(nb.events),
                   "leads": len(astra), "relevant": len(rel), "expected": gt["expected_case_hypothesis"],
                   "leading": res["case_hypotheses"]["leading"], "runtime_s": round(dt, 4)}
            if kind == "incident":
                for k in ks:
                    for name, r in (("astra", astra), ("baseline", base)):
                        top = r[:k]
                        row[f"{name}_p@{k}"] = sum(a in rel for a in top) / k
                        row[f"{name}_r@{k}"] = sum(a in rel for a in top) / len(rel) if rel else None
                        row[f"{name}_service_in_top{k}"] = any(a in svc for a in top)
                row["astra_ap"], row["baseline_ap"] = _ap(astra, rel), _ap(base, rel)
            per.append(row)

    def mean(xs):
        xs = [x for x in xs if x is not None]
        return round(sum(xs) / len(xs), 4) if xs else None
    inc = [r for r in per if r["kind"] == "incident"]
    ben = [r for r in per if r["kind"] == "benign"]
    agg: dict[str, Any] = {"incident_scenarios": len(inc), "benign_scenarios": len(ben),
                           "insufficient_scenarios": sum(1 for r in per if r["kind"] == "insufficient")}
    for k in ks:
        for name in ("astra", "baseline"):
            agg[f"{name}_precision_at_{k}"] = mean(r[f"{name}_p@{k}"] for r in inc)
            agg[f"{name}_recall_at_{k}"] = mean(r[f"{name}_r@{k}"] for r in inc)
            agg[f"{name}_service_in_top{k}_rate"] = mean(1.0 if r[f"{name}_service_in_top{k}"] else 0.0 for r in inc)
    agg["astra_average_precision"] = mean(r["astra_ap"] for r in inc)
    agg["baseline_average_precision"] = mean(r["baseline_ap"] for r in inc)
    agg["case_hypothesis_accuracy"] = mean(1.0 if r["leading"] == r["expected"] else 0.0 for r in per)
    agg["case_hypothesis_n"] = len(per)
    agg["benign_false_positive_rate"] = mean(1.0 if r["leading"] == "H1" else 0.0 for r in ben)
    agg["mean_runtime_s"] = mean(r["runtime_s"] for r in per)
    agg["max_runtime_s"] = max((r["runtime_s"] for r in per), default=None)
    k0 = ks[-1]
    return {
        "benchmark_type": "controlled_synthetic_evaluation_not_real_world_validation",
        "generated_at": datetime.now(timezone.utc).isoformat(), "generator": "astra-sim-v1",
        "seeds": seeds, "ks": list(ks), "kinds": list(kinds), "aggregate": agg, "scenarios": per,
        "environment": {"python": platform.python_version(), "machine": platform.machine(), "system": platform.system()},
        "baseline": "time-ignoring BFS reachability from the origin ranked by hop count",
        "definitions": {
            "relevant": "addresses on the generated incident splitting tree (service hubs excluded)",
            "precision_at_k": "relevant in top k / k (incident scenarios)",
            "recall_at_k": "relevant in top k / number of relevant addresses (incident scenarios)",
            "benign_false_positive_rate": "benign scenarios whose leading case hypothesis is H1 / benign scenarios",
            "case_hypothesis_accuracy": "scenarios whose leading case hypothesis equals the generator's expected label / all scenarios",
        },
        "summary": (f"{len(per)} synthetic scenarios ({len(inc)} incident, {len(ben)} benign). "
                    f"precision@{k0}: ASTRA {agg[f'astra_precision_at_{k0}']} vs baseline {agg[f'baseline_precision_at_{k0}']}; "
                    f"service hub in top {k0}: ASTRA {agg[f'astra_service_in_top{k0}_rate']} vs baseline "
                    f"{agg[f'baseline_service_in_top{k0}_rate']}; case-hypothesis accuracy {agg['case_hypothesis_accuracy']}; "
                    f"benign FPR {agg['benign_false_positive_rate']}."),
        "limitations": ["Synthetic generator written by the same team as the engine: results show internal consistency, "
                        "not real-world effectiveness.", "No real labelled incidents were available."],
    }
