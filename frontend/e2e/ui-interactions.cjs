// UI end-to-end interaction checks against the running integrated stack.
const { chromium } = require('playwright');
const fs = require('fs');
const HS = process.env.ASTRA_CHROMIUM || undefined; // optional: path to a Chromium/headless_shell binary
(async () => {
  const base = process.argv[2]; const out = process.argv[3]; fs.mkdirSync(out, { recursive: true });
  const browser = await chromium.launch({ executablePath: HS, args: ['--use-gl=swiftshader', '--enable-webgl', '--ignore-gpu-blocklist'] });
  const ctx = await browser.newContext({ viewport: { width: 1440, height: 900 } });
  const page = await ctx.newPage();
  const results = []; const errors = []; const apiCalls = [];
  page.on('pageerror', e => errors.push(e.message));
  page.on('request', r => { const u = r.url(); if (u.includes('/api/') || u.endsWith('/health')) apiCalls.push(`${r.method()} ${u.replace(base, '')}`); });
  const check = (name, ok, extra = '') => { results.push({ name, ok: !!ok, extra }); console.log(`${ok ? 'PASS' : 'FAIL'} ${name}${extra ? '  ' + extra : ''}`); };
  const nav = async (label) => { await page.locator(`.astra-dock-host [aria-label="${label}"]`).first().click(); await page.waitForTimeout(900); };
  await page.goto(base, { waitUntil: 'networkidle' });
  await page.click('.landing-enter-dock'); await page.waitForTimeout(2500);
  const analysis = await (await page.request.get(`${base}/api/investigations/inv-ghost_attacks_synthetic_v1/analysis`)).json();
  const edges = analysis.analysis.graph_stats.edges;
  const metric = await page.locator('.metric-card .metric-value').first().innerText();
  check('1 overview metric equals backend graph_stats.edges', metric.trim() === String(edges), `${metric} vs ${edges}`);
  check('1b footer shows synthetic data label', (await page.locator('.app-footer').innerText()).includes('SYNTHETIC / SIMULATED'));
  const topLead = analysis.analysis.leads[0];
  const firstSignal = await page.locator('.signal-row .signal-score strong').first().innerText();
  check('2 top priority signal equals backend top lead score', Number(firstSignal) === Math.round(topLead.priority_score), `${firstSignal} vs ${topLead.priority_score}`);
  await nav('Graph');
  const n0 = await page.locator('.graph-node').count();
  await page.getByRole('button', { name: 'Expand graph' }).click(); await page.waitForTimeout(600);
  const n1 = await page.locator('.graph-node').count();
  check('3 graph renders backend nodes; expand never shrinks', n0 > 1 && n1 >= n0, `${n0} -> ${n1}`);
  await page.screenshot({ path: `${out}/graph.png` });
  await nav('Evidence');
  const before = apiCalls.filter(c => c.includes('/sensitivity')).length;
  await page.locator('.sensitivity-panel .switch').click();
  await page.waitForFunction(() => document.querySelector('.sensitivity-explanation p')?.innerText.includes('Engine re-run complete'), null, { timeout: 15000 });
  const after = apiCalls.filter(c => c.includes('/sensitivity')).length;
  const txt = await page.locator('.sensitivity-explanation p').innerText();
  check('4 sensitivity toggle POSTs to backend and shows recomputed result', after === before + 1 && /score .* → /.test(txt), txt.slice(0, 120));
  await page.screenshot({ path: `${out}/evidence-sensitivity.png` });
  await nav('Hypotheses');
  const rank = await page.locator('.rank-change strong').innerText();
  check('5 hypotheses page shows before/after leading score', /\d+\s*→?\s*\d+/.test(rank.replace(/\n/g, ' ')), rank.replace(/\n/g, ' '));
  await page.getByRole('button', { name: 'Reset comparison' }).click(); await page.waitForTimeout(300);
  await nav('Timeline');
  await page.waitForTimeout(1200);
  const slider = page.locator('input[type=range]');
  await slider.fill('5'); await page.waitForTimeout(1500);
  const replays = apiCalls.filter(c => c.includes('/replay?cutoff='));
  const warn = await page.locator('.replay-warning p').innerText();
  check('6 replay slider calls backend with a cutoff and excludes later events', replays.length >= 2 && /^\d+ later events/.test(warn), `${replays.slice(-1)[0]} | ${warn.slice(0, 60)}`);
  await page.screenshot({ path: `${out}/replay-early.png` });
  await nav('Evaluation lab');
  await page.waitForFunction(() => document.querySelector('.metrics-grid .metric-value')?.innerText.includes('%'), null, { timeout: 60000 });
  check('7 evaluation page renders measured benchmark', (await page.locator('.evaluation-warning').innerText()).includes('SYNTHETIC scenarios'));
  await nav('Casebook');
  const [popup] = await Promise.all([ctx.waitForEvent('page'), page.getByRole('button', { name: 'Preview report' }).click()]);
  await popup.waitForLoadState(); const rtxt = await popup.locator('body').innerText();
  check('8 report preview is the backend HTML casebook with synthetic label', rtxt.includes('SYNTHETIC / SIMULATED') && rtxt.includes('Ranked candidate leads'));
  await popup.close();
  await nav('Settings');
  await page.getByRole('button', { name: 'Simulation' }).click();
  await page.fill('input[aria-label="Simulation seed"]', '7');
  await page.selectOption('select[aria-label="Scenario kind"]', 'benign');
  await page.getByRole('button', { name: 'Open investigation' }).last().click();
  await page.waitForFunction(() => document.querySelector('.case-context')?.innerText.includes('sim-benign-7'), null, { timeout: 20000 });
  check('9 settings creates a deterministic simulation via backend and opens it', true, await page.locator('.case-context').innerText());
  await nav('Hypotheses');
  const leadCard = await page.locator('.hypothesis-primary .hypothesis-id').innerText();
  check('10 benign simulation: leading hypothesis computed as H2', leadCard.trim() === 'H2', leadCard);
  await page.getByRole('button', { name: 'Live wallet' }).count();
  await nav('Settings');
  await page.getByRole('button', { name: 'Live wallet' }).click();
  await page.fill('input[aria-label="Wallet address"]', '0x00000000000000000000000000000000000c0de1');
  await page.getByRole('button', { name: 'Open investigation' }).last().click();
  await page.waitForFunction(() => document.querySelector('.toast')?.innerText.includes('PROVIDER_NOT_CONFIGURED'), null, { timeout: 10000 });
  check('11 live wallet without key shows explicit provider error (no silent synthetic data)', (await page.locator('.case-context').innerText()).includes('sim-benign-7'), await page.locator('.toast').innerText());
  await page.screenshot({ path: `${out}/settings.png`, fullPage: true });
  check('12 no uncaught page errors', errors.length === 0, errors.join(' | ').slice(0, 200));
  fs.writeFileSync(`${out}/interaction-results.json`, JSON.stringify({ results, apiCalls: [...new Set(apiCalls)] }, null, 2));
  await browser.close();
  process.exit(results.every(r => r.ok) ? 0 : 1);
})();
